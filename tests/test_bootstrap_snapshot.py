import os
import hashlib
import subprocess
from pathlib import Path
import pytest

import sys

from release_meta import expected_banner_line

REPO_ROOT = Path(__file__).parent.parent.resolve()
BOOTSTRAP_C = REPO_ROOT / "bootstrap.c"
BOOTSTRAP_BAT = REPO_ROOT / "scripts" / "bootstrap.bat"
BOOTSTRAP_SH = REPO_ROOT / "scripts" / "bootstrap.sh"
VELO_EXE = REPO_ROOT / "bin" / ("velo.exe" if sys.platform == "win32" else "velo")
MAIN_VL = REPO_ROOT / "src" / "main.vl"

def get_env():
    env = os.environ.copy()
    if sys.platform == "win32":
        env["PATH"] = r"C:\msys64\ucrt64\bin;" + env.get("PATH", "")
    return env

def test_bootstrap_c_file_integrity():
    """Verify that bootstrap.c exists, is substantial, has no UTF-8 BOM, and has the right header."""
    assert BOOTSTRAP_C.exists(), "bootstrap.c must exist at repository root"
    raw_data = BOOTSTRAP_C.read_bytes()
    assert len(raw_data) > 500_000, f"bootstrap.c should be > 500KB, got {len(raw_data)} bytes"
    assert not raw_data.startswith(b"\xef\xbb\xbf"), "bootstrap.c must not contain a UTF-8 BOM"

    text = raw_data.decode("utf-8")
    lines = text.splitlines()
    assert lines[0] == "/* Generated by Velo Stage 2 Self-Hosted Compiler */"
    assert lines[1] == '#include "velo_runtime.h"'

def test_bootstrap_scripts_exist():
    """Verify that scripts/bootstrap.bat and scripts/bootstrap.sh exist."""
    assert BOOTSTRAP_BAT.exists(), "scripts/bootstrap.bat must exist"
    assert BOOTSTRAP_SH.exists(), "scripts/bootstrap.sh must exist"
    bat_content = BOOTSTRAP_BAT.read_text(encoding="utf-8")
    assert "bootstrap.c" in bat_content
    assert "bin\\velo.exe" in bat_content

    sh_content = BOOTSTRAP_SH.read_text(encoding="utf-8")
    assert "bootstrap.c" in sh_content
    assert "bin/velo" in sh_content

def test_emit_c_output_flag(tmp_path):
    """Verify that 'velo emit-c <src> -o <out>' writes to file correctly."""
    out_c = tmp_path / "hello.c"
    res = subprocess.run(
        [str(VELO_EXE), "emit-c", "examples/01_hello.vl", "-o", str(out_c)],
        cwd=str(REPO_ROOT),
        capture_output=True,
        text=True,
        env=get_env()
    )
    assert res.returncode == 0, f"emit-c with -o failed:\n{res.stderr}"
    assert out_c.exists(), "Output file was not created"
    c_content = out_c.read_text(encoding="utf-8")
    assert "/* Generated by Velo Stage 2 Self-Hosted Compiler */" in c_content
    assert "velo_io_println" in c_content or "Hello, world!!" in c_content

def test_bootstrap_c_compilation(tmp_path):
    """Verify that bootstrap.c compiles cleanly with ambient GCC into a functional standalone compiler."""
    test_exe = tmp_path / ("velo_boot.exe" if sys.platform == "win32" else "velo_boot")
    gcc_cmd = [
        "gcc", "-O2", "-std=c99",
        "-I", str(REPO_ROOT / "runtime"),
        "-I", str(REPO_ROOT / "velo" / "runtime"),
        str(BOOTSTRAP_C),
        "-o", str(test_exe)
    ]
    if sys.platform != "win32":
        gcc_cmd.extend(["-lm", "-lpthread"])
    res = subprocess.run(gcc_cmd, cwd=str(REPO_ROOT), capture_output=True, text=True, env=get_env())
    assert res.returncode == 0, f"Compilation of bootstrap.c failed:\n{res.stderr}"
    assert test_exe.exists(), "Target executable was not produced"

    res_ver = subprocess.run([str(test_exe), "version"], capture_output=True, text=True, env=get_env())
    assert res_ver.returncode == 0
    assert expected_banner_line() in res_ver.stdout

def test_bootstrap_c_determinism(tmp_path):
    """Verify that bootstrap.c matches the current emit-c -o output of src/main.vl."""
    fresh_c = tmp_path / "fresh_bootstrap.c"
    res = subprocess.run(
        [str(VELO_EXE), "emit-c", "src/main.vl", "-o", str(fresh_c)],
        cwd=str(REPO_ROOT),
        capture_output=True,
        text=True,
        env=get_env()
    )
    assert res.returncode == 0, f"emit-c failed:\n{res.stderr}"
    assert fresh_c.exists(), "fresh_bootstrap.c was not created"
    current_sha256 = hashlib.sha256(fresh_c.read_bytes()).hexdigest()
    bootstrap_sha256 = hashlib.sha256(BOOTSTRAP_C.read_bytes()).hexdigest()
    assert current_sha256 == bootstrap_sha256, (
        f"bootstrap.c is out of sync with current src/main.vl emit-c output!\n"
        f"Current SHA256:   {current_sha256}\n"
        f"bootstrap SHA256: {bootstrap_sha256}"
    )
