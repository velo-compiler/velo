"""tests/test_roadmap_generator.py — Regression tests for docs/ROADMAP.md generator.

Validates Task 84.5 and Phase 84 exit criteria:
  "docs/ROADMAP.md is generated from gaps.md and fails CI when stale."
"""

import subprocess
import sys
from pathlib import Path
import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
GEN_ROADMAP_SCRIPT = REPO_ROOT / "scripts" / "gen_roadmap.py"
GAPS_MD = REPO_ROOT / "gaps.md"
TARGET_ROADMAP = REPO_ROOT / "docs" / "ROADMAP.md"

pytestmark = pytest.mark.fast


def test_roadmap_script_exists():
    """Verify scripts/gen_roadmap.py and docs/ROADMAP.md exist."""
    assert GEN_ROADMAP_SCRIPT.exists(), f"Missing {GEN_ROADMAP_SCRIPT}"
    assert TARGET_ROADMAP.exists(), f"Missing {TARGET_ROADMAP}"
    assert GAPS_MD.exists(), f"Missing {GAPS_MD}"


def test_roadmap_check_exits_zero():
    """Verify python scripts/gen_roadmap.py --check exits 0 on committed tree."""
    res = subprocess.run(
        [sys.executable, str(GEN_ROADMAP_SCRIPT), "--check"],
        cwd=str(REPO_ROOT),
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    assert res.returncode == 0, f"Roadmap check failed:\nstdout: {res.stdout}\nstderr: {res.stderr}"
    assert "PASS: docs/ROADMAP.md is up to date with gaps.md." in res.stdout


def test_roadmap_stdout_matches_file():
    """Verify python scripts/gen_roadmap.py --stdout matches docs/ROADMAP.md."""
    res = subprocess.run(
        [sys.executable, str(GEN_ROADMAP_SCRIPT), "--stdout"],
        cwd=str(REPO_ROOT),
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    assert res.returncode == 0
    expected = TARGET_ROADMAP.read_text(encoding="utf-8")
    assert res.stdout.replace("\r\n", "\n") == expected.replace("\r\n", "\n")


def test_roadmap_drift_detection(monkeypatch, tmp_path):
    """Verify scripts/gen_roadmap.py --check exits with code 1 and prints diff on drift."""
    # Import the script module
    sys.path.insert(0, str(REPO_ROOT / "scripts"))
    import gen_roadmap

    fake_roadmap = tmp_path / "ROADMAP.md"
    fake_roadmap.write_text("This is stale and outdated content.\n", encoding="utf-8")

    monkeypatch.setattr(gen_roadmap, "TARGET_ROADMAP", fake_roadmap)
    monkeypatch.setattr(sys, "argv", ["gen_roadmap.py", "--check"])

    code = gen_roadmap.main()
    assert code == 1


def test_roadmap_structural_elements():
    """Verify docs/ROADMAP.md contains all required sections and links."""
    content = TARGET_ROADMAP.read_text(encoding="utf-8")

    # Header and warning banner
    assert "AUTO-GENERATED FILE -- DO NOT EDIT DIRECTLY" in content
    assert "Generated by scripts/gen_roadmap.py from gaps.md" in content
    assert "# 🗺️ Velo Engineering Roadmap & Release Registry" in content

    # High-level metrics
    assert "## 📊 High-Level Release Status" in content
    assert "Current Baseline:" in content
    assert "Phase Completion:" in content
    assert "Task Execution:" in content

    # Strategic Waves
    assert "## 🌊 Strategic Execution Waves" in content
    assert "Wave A:" in content
    assert "Wave B:" in content
    assert "Wave C:" in content

    # Progress Matrix
    assert "## 📋 Phase Progress Matrix" in content
    assert "| Phase | Milestone Title | Tier | Status | Tasks | Progress |" in content
    for p in range(70, 86):
        assert f"| **{p}** |" in content, f"Phase {p} missing from roadmap matrix"

    # Completed Archives and Contribution Guide
    assert "## 📦 Completed Milestone Archives" in content
    assert "## 🛠️ Contributing to the Roadmap" in content
    assert "GOVERNANCE.md" in content
    assert "ISSUE_TEMPLATE" in content
    assert "PULL_REQUEST_TEMPLATE" in content
